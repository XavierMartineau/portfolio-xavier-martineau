// Etat de langue et index des noeuds textuels traduisibles.
const languageStorageKey = "portfolio-language";
const supportedLanguages = ["fr", "en"];
const savedLanguage = localStorage.getItem(languageStorageKey);
const currentLanguage = supportedLanguages.includes(savedLanguage)
  ? savedLanguage
  : "fr";
const originalTextByNode = new WeakMap();
const translatableTextNodes = [];
const englishToFrench = new Map(
  Object.entries(translations.en).map(([french, english]) => [english, french]),
);

const normalizeText = (text) => text.replace(/\s+/g, " ").trim();
const preserveWhitespace = (source, replacement) => {
  const leadingWhitespace = source.match(/^\s*/)?.[0] || "";
  const trailingWhitespace = source.match(/\s*$/)?.[0] || "";
  return `${leadingWhitespace}${replacement}${trailingWhitespace}`;
};

// Traduction du contenu et mise a jour des controles de langue.
const translateTextNodes = (language) => {
  document.querySelectorAll("[aria-label]").forEach((element) => {
    const originalLabel = element.dataset.i18nLabel || element.ariaLabel;
    if (!element.dataset.i18nLabel) {
      element.dataset.i18nLabel = originalLabel;
    }

    const translatedLabel = translations.en[originalLabel];
    if (translatedLabel) {
      element.ariaLabel = language === "en" ? translatedLabel : originalLabel;
    }
  });

  document.querySelectorAll("[data-i18n-label]").forEach((element) => {
    const key = element.dataset.i18nLabel;
    element.setAttribute(
      "aria-label",
      language === "en" ? translations.en[key] || key : key,
    );
  });

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = language === "en" ? translations.en[key] || key : key;
  });

  if (language !== "en") {
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    const textNodes = [];
    while (walker.nextNode()) {
      textNodes.push(walker.currentNode);
    }

    textNodes.forEach((node) => {
      if (
        node.parentElement.closest(
          "script, style, [data-i18n], .language-switcher",
        )
      ) {
        return;
      }

      const currentText = normalizeText(node.nodeValue);
      const hasSectionPrefix = currentText.startsWith("// ");
      const englishKey = hasSectionPrefix ? currentText.slice(3) : currentText;
      const frenchText = englishToFrench.get(englishKey);
      const originalText = originalTextByNode.get(node);
      const originalKey = originalText
        ? normalizeText(originalText).replace(/^\/\/ /, "")
        : "";
      const restoredFrenchText = frenchText || englishToFrench.get(originalKey);

      if (restoredFrenchText) {
        const restoredText = hasSectionPrefix
          ? `// ${restoredFrenchText}`
          : restoredFrenchText;
        node.nodeValue = preserveWhitespace(node.nodeValue, restoredText);
      } else if (originalTextByNode.has(node)) {
        node.nodeValue = originalText;
      }
    });
    return;
  }

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  textNodes.forEach((node) => {
    if (
      node.parentElement.closest(
        "script, style, [data-i18n], .language-switcher",
      )
    ) {
      return;
    }

    if (!originalTextByNode.has(node)) {
      originalTextByNode.set(node, node.nodeValue);
      translatableTextNodes.push(node);
    }

    let originalNodeText = originalTextByNode.get(node);
    const storedText = normalizeText(originalNodeText);
    const storedKey = storedText.startsWith("// ")
      ? storedText.slice(3)
      : storedText;
    const storedTranslation = translations.en[storedKey];
    const storedTranslatedText = storedTranslation
      ? storedText.startsWith("// ")
        ? `// ${storedTranslation}`
        : storedTranslation
      : null;

    if (
      normalizeText(node.nodeValue) !== normalizeText(originalNodeText) &&
      normalizeText(node.nodeValue) !==
        normalizeText(storedTranslatedText || "")
    ) {
      originalNodeText = node.nodeValue;
      originalTextByNode.set(node, originalNodeText);
    }

    const originalText = normalizeText(originalNodeText);
    const hasSectionPrefix = originalText.startsWith("// ");
    const translationKey = hasSectionPrefix
      ? originalText.slice(3)
      : originalText;
    const translatedText = translations.en[translationKey];
    if (translatedText) {
      const formattedTranslation = hasSectionPrefix
        ? `// ${translatedText}`
        : translatedText;
      node.nodeValue = preserveWhitespace(node.nodeValue, formattedTranslation);
    }
  });
};

const updateLanguageControls = (language) => {
  document.documentElement.lang = language;
  document.querySelectorAll(".language-switcher button").forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
    button.setAttribute(
      "aria-label",
      button.dataset.language === "fr"
        ? "Afficher le français"
        : "Show English",
    );
  });
};

const setLanguage = (language) => {
  if (!supportedLanguages.includes(language)) {
    return;
  }

  localStorage.setItem(languageStorageKey, language);
  document.documentElement.lang = language;
  translateTextNodes(language);
  updateLanguageControls(language);
};

window.translatePortfolio = (language = document.documentElement.lang) => {
  if (supportedLanguages.includes(language)) {
    translateTextNodes(language);
    updateLanguageControls(language);
  }
};

const languageSwitcher = document.querySelector(".language-switcher");

languageSwitcher?.addEventListener("animationend", (event) => {
  if (event.animationName === "language-switch-transition") {
    languageSwitcher.classList.remove("is-switching");
  }
});

document.querySelectorAll(".language-switcher button").forEach((button) => {
  button.addEventListener("click", () => {
    if (languageSwitcher) {
      languageSwitcher.classList.remove("is-switching");
      void languageSwitcher.offsetWidth;
      languageSwitcher.classList.add("is-switching");
    }
    setLanguage(button.dataset.language);
  });
});

setLanguage(currentLanguage);

// Controle de navigation retour en haut.
const backToTop = document.createElement("button");
backToTop.className = "back-to-top";
backToTop.type = "button";
backToTop.textContent = "↑";
document.body.appendChild(backToTop);

const updateBackToTop = () => {
  backToTop.classList.toggle("is-visible", window.scrollY > 400);
  backToTop.setAttribute(
    "aria-label",
    document.documentElement.lang === "en" ? "Back to top" : "Retour en haut",
  );
  const label = document.documentElement.lang === "en" ? "TOP ↑" : "HAUT ↑";
  backToTop.textContent = label;
  backToTop.title = label;
};

backToTop.addEventListener("click", () => {
  window.scrollTo({
    top: 0,
    behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches
      ? "auto"
      : "smooth",
  });
});

window.addEventListener("scroll", updateBackToTop, { passive: true });
updateBackToTop();

// Observation des ajouts DOM pour maintenir les traductions synchronisees.
let translationObserverTimer;
const translationObserver = new MutationObserver(() => {
  if (document.documentElement.lang !== "en") {
    return;
  }

  window.clearTimeout(translationObserverTimer);
  translationObserverTimer = window.setTimeout(() => {
    if (document.documentElement.lang === "en") {
      translateTextNodes("en");
    }
  }, 0);
});

translationObserver.observe(document.body, {
  childList: true,
  characterData: true,
  subtree: true,
});
